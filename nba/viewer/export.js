// Writes nba/viewer/data.js from the workbook so the offline viewer opens
// straight from disk (browsers won't let a file:// page fetch the .xlsx).
//
//   node nba/viewer/export.js [path/to/workbook.xlsx]
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..', '..');
require(path.join(root, 'src/lib/xlsx-reader.js'));
require(path.join(root, 'src/nba/model.js'));
require(path.join(root, 'src/nba/workbook.js'));

const source = process.argv[2] || path.join(root, 'nba', '2026-27-NBA-Roto-Values.xlsx');
const bytes = fs.readFileSync(source);

globalThis.YDR.nbaWorkbook.importWorkbook(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.length))
  .then((board) => {
    const data = { ...board, fileName: path.basename(source), exportedAt: new Date().toISOString() };
    const out = path.join(__dirname, 'data.js');
    fs.writeFileSync(out, `// Generated by nba/viewer/export.js from ${data.fileName} — do not edit.\nglobalThis.NBA_BOARD = ${JSON.stringify(data)};\n`);
    console.log(`wrote ${path.relative(root, out)}: ${board.players.length} players, ${board.schedule.length / 2} games`);
  })
  .catch((error) => {
    console.error(`couldn't read ${source}: ${error.message}`);
    process.exit(1);
  });
